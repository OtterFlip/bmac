# Host-side guest networking for one mox host:
#
# - the shared guest gateway: GUEST_GATEWAY_IP with GUEST_GATEWAY_MAC on a
#   veth pair whose other end is a port of the private bridge. Every mox host
#   has the same address and MAC, and bridge rules on the physical private-VLAN
#   port keep both off the VLAN, so each host's gateway is seen only by the
#   guests running on it;
# - outbound NAT of the VM slots through this host's public interface, and of
#   traffic another mox host hands over while its own connection is down;
# - the guest-egress routing table (its default route is switched by
#   egress_health.py) and one table per other mox host for probing and using
#   that host as the fallback.
#
#   guest_network.sh configure ENV_FILE   install the settings, units and rules
#   guest_network.sh apply                (boot) build the runtime state
#   guest_network.sh ensure-gateway       recreate the gateway interface if needed
#   guest_network.sh verify               check everything is in place

set -Eeuo pipefail

SETTINGS=/etc/app-ha/guest-network.env
NFT_FILE=/etc/nftables.d/app-ha-guest-network.nft
SYSCTL_FILE=/etc/sysctl.d/91-app-ha-guest-network.conf
PRIVATE_CFG=/etc/network/interfaces.d/app-ha-private.cfg
GATEWAY_IF=bmacgw0
GATEWAY_PEER=bmacgw0br
GUEST_EGRESS_TABLE=200
PEER_TABLE_BASE=200
PEER_MARK_BASE=0x100
RULE_PRIORITY=1000
INSTALL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FIREWALL_COMMENT_PREFIX="app-ha managed guest network"

die() {
  printf 'guest_network: %s\n' "$*" >&2
  exit 1
}

load_settings() {
  local file="${1:-$SETTINGS}" line key value
  [[ -f "$file" && ! -L "$file" ]] || die "settings file is missing: $file"
  while IFS= read -r line || [[ -n "$line" ]]; do
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" =~ ^(BMAC_[A-Z0-9_]+)=(.*)$ ]] || die "invalid settings line: $line"
    key="${BASH_REMATCH[1]}"
    value="${BASH_REMATCH[2]}"
    printf -v "$key" '%s' "$value"
  done <"$file"
  local name
  for name in BMAC_HOST BMAC_MOX_INDEX BMAC_PRIVATE_BRIDGE BMAC_PRIVATE_NIC \
    BMAC_PRIVATE_IP BMAC_PUBLIC_IF BMAC_PUBLIC_NIC BMAC_PUBLIC_IP BMAC_PUBLIC_GATEWAY \
    BMAC_GUEST_GATEWAY_IP BMAC_GUEST_GATEWAY_MAC BMAC_SLOT_FIRST BMAC_SLOT_LAST \
    BMAC_MOX_FIRST BMAC_MAX_MOX_HOSTS; do
    [[ -n "${!name:-}" ]] || die "$name is missing from $file"
  done
  [[ "$BMAC_HOST" =~ ^mox([1-9]|10)$ && "${BMAC_HOST#mox}" == "$BMAC_MOX_INDEX" ]] ||
    die "BMAC_HOST and BMAC_MOX_INDEX disagree"
  [[ "$BMAC_MAX_MOX_HOSTS" =~ ^([1-9]|10)$ ]] || die "invalid BMAC_MAX_MOX_HOSTS"
  [[ "${BMAC_GUEST_GATEWAY_MAC,,}" =~ ^[0-9a-f][26ae](:[0-9a-f]{2}){5}$ ]] ||
    die "BMAC_GUEST_GATEWAY_MAC is not a locally administered unicast MAC"
  BMAC_GUEST_GATEWAY_MAC="${BMAC_GUEST_GATEWAY_MAC,,}"
  local address
  for address in BMAC_PRIVATE_IP BMAC_PUBLIC_IP BMAC_PUBLIC_GATEWAY \
    BMAC_GUEST_GATEWAY_IP BMAC_SLOT_FIRST BMAC_SLOT_LAST BMAC_MOX_FIRST; do
    [[ "${!address}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "$address is not IPv4"
  done
  for name in BMAC_PRIVATE_BRIDGE BMAC_PRIVATE_NIC BMAC_PUBLIC_IF BMAC_PUBLIC_NIC; do
    [[ "${!name}" =~ ^[A-Za-z0-9][A-Za-z0-9_.-]{0,14}$ ]] || die "$name is not an interface name"
  done
}

# The private address of moxN.
mox_address() {
  local index="$1" prefix="${BMAC_MOX_FIRST%.*}" first="${BMAC_MOX_FIRST##*.}"
  printf '%s.%s\n' "$prefix" "$((first + index - 1))"
}

mox_last() {
  mox_address "$BMAC_MAX_MOX_HOSTS"
}

render_nft() {
  local slots="${BMAC_SLOT_FIRST}-${BMAC_SLOT_LAST}"
  local moxes="${BMAC_MOX_FIRST}-$(mox_last)"
  cat <<EOF
# Managed by BMAC guest_network.sh; regenerated by host setup and by the
# "Sync cluster with cluster.conf" operation.

# Keep the shared guest gateway (${BMAC_GUEST_GATEWAY_IP}, ${BMAC_GUEST_GATEWAY_MAC})
# off the private VLAN, so only this host's own guests ever see it.
table bridge app_ha_guest_gateway {
  chain forward {
    type filter hook forward priority -200; policy accept;
    oifname "${BMAC_PRIVATE_NIC}" ether saddr ${BMAC_GUEST_GATEWAY_MAC} counter drop
    oifname "${BMAC_PRIVATE_NIC}" arp saddr ip ${BMAC_GUEST_GATEWAY_IP} counter drop
    oifname "${BMAC_PRIVATE_NIC}" arp daddr ip ${BMAC_GUEST_GATEWAY_IP} counter drop
    iifname "${BMAC_PRIVATE_NIC}" ether daddr ${BMAC_GUEST_GATEWAY_MAC} counter drop
    iifname "${BMAC_PRIVATE_NIC}" arp saddr ip ${BMAC_GUEST_GATEWAY_IP} counter drop
    iifname "${BMAC_PRIVATE_NIC}" arp daddr ip ${BMAC_GUEST_GATEWAY_IP} counter drop
  }
}

# Outbound NAT for this host's guests, and for traffic another mox host
# hands over (its guests, or its own probes) while its connection is down.
table ip app_ha_guest_egress {
  set guest_sources {
    type ipv4_addr
    flags interval
    elements = { ${slots}, ${moxes} }
  }

  chain forward {
    type filter hook forward priority -190; policy accept;
    iifname "${GATEWAY_IF}" ip saddr ${slots} counter accept
    iifname "${BMAC_PRIVATE_BRIDGE}" oifname "${BMAC_PUBLIC_IF}" ip saddr @guest_sources counter accept
    iifname "${BMAC_PUBLIC_IF}" oifname "${BMAC_PRIVATE_BRIDGE}" ct state established,related counter accept
  }

  chain postrouting {
    type nat hook postrouting priority srcnat; policy accept;
    oifname "${BMAC_PUBLIC_IF}" ip saddr @guest_sources counter masquerade
  }
}
EOF
}

render_sysctl() {
  cat <<EOF
# Managed by BMAC guest_network.sh.
net.ipv4.ip_forward=1
# Guests' packets arrive on ${GATEWAY_IF} but their addresses route via the
# bridge, so strict reverse-path filtering would drop them.
net.ipv4.conf.all.rp_filter=2
net.ipv4.conf.default.rp_filter=2
# Only ${GATEWAY_IF} may answer ARP for the gateway address: the bridge must
# not answer for addresses it doesn't hold.
net.ipv4.conf.all.arp_ignore=1
net.ipv4.conf.all.arp_announce=2
# Forwarding a guest's packet to a fallback host over the same VLAN must not
# tell the guest to bypass the gateway.
net.ipv4.conf.all.send_redirects=0
net.ipv4.conf.default.send_redirects=0
# During fallback this host sees only the outbound half of guest flows.
net.netfilter.nf_conntrack_tcp_loose=1
EOF
}

ensure_gateway() {
  local bridge="$BMAC_PRIVATE_BRIDGE"
  [[ -d "/sys/class/net/$bridge/bridge" ]] || die "private bridge $bridge is missing"
  if [[ ! -e "/sys/class/net/$GATEWAY_IF" ]]; then
    ip link add "$GATEWAY_IF" type veth peer name "$GATEWAY_PEER"
  fi
  [[ -e "/sys/class/net/$GATEWAY_PEER" ]] || die "$GATEWAY_PEER is missing"
  if [[ "$(<"/sys/class/net/$GATEWAY_IF/address")" != "$BMAC_GUEST_GATEWAY_MAC" ]]; then
    ip link set dev "$GATEWAY_IF" down
    ip link set dev "$GATEWAY_IF" address "$BMAC_GUEST_GATEWAY_MAC"
  fi
  sysctl -qw "net.ipv4.conf.${GATEWAY_IF}.rp_filter=2"
  sysctl -qw "net.ipv4.conf.${GATEWAY_IF}.send_redirects=0"
  if ! ip -4 -o address show dev "$GATEWAY_IF" | grep -Fq " ${BMAC_GUEST_GATEWAY_IP}/32 "; then
    ip -4 address flush dev "$GATEWAY_IF"
    ip address add "${BMAC_GUEST_GATEWAY_IP}/32" dev "$GATEWAY_IF"
  fi
  local master=""
  master="$(basename "$(readlink -f "/sys/class/net/$GATEWAY_PEER/master" 2>/dev/null || true)")"
  [[ "$master" == "$bridge" ]] || ip link set dev "$GATEWAY_PEER" master "$bridge"
  ip link set dev "$GATEWAY_PEER" up
  ip link set dev "$GATEWAY_IF" up
}

ensure_routing() {
  local index peer mark table
  ip rule show | grep -Fq "iif $GATEWAY_IF lookup $GUEST_EGRESS_TABLE" ||
    ip rule add priority "$RULE_PRIORITY" iif "$GATEWAY_IF" lookup "$GUEST_EGRESS_TABLE"
  # The health service owns the guest-egress default route; set the normal
  # one only when the table is empty (at boot).
  if [[ -z "$(ip -4 route show table "$GUEST_EGRESS_TABLE" default)" ]]; then
    ip route replace default via "$BMAC_PUBLIC_GATEWAY" dev "$BMAC_PUBLIC_IF" \
      table "$GUEST_EGRESS_TABLE"
  fi
  for ((index = 1; index <= 10; index += 1)); do
    table=$((PEER_TABLE_BASE + index))
    mark=$(printf '0x%x' $((PEER_MARK_BASE + index)))
    if ((index == BMAC_MOX_INDEX || index > BMAC_MAX_MOX_HOSTS)); then
      ip rule del fwmark "$mark" lookup "$table" 2>/dev/null || true
      ip route flush table "$table" 2>/dev/null || true
      continue
    fi
    peer="$(mox_address "$index")"
    ip route replace default via "$peer" dev "$BMAC_PRIVATE_BRIDGE" table "$table"
    ip rule show | grep -Fq "fwmark $mark lookup $table" ||
      ip rule add priority $((RULE_PRIORITY + index)) fwmark "$mark" lookup "$table"
  done
}

load_nft() {
  local table
  for table in "bridge app_ha_guest_gateway" "ip app_ha_guest_egress"; do
    # shellcheck disable=SC2086
    nft list table $table >/dev/null 2>&1 && nft delete table $table
  done
  nft -f "$NFT_FILE"
}

command_apply() {
  load_settings
  sysctl -q -p "$SYSCTL_FILE" >/dev/null
  ensure_gateway
  ensure_routing
  load_nft
}

# Proxmox's host firewall may also filter forwarded traffic, so it gets the
# same allowance as the nft forward chain.
reconcile_firewall_rules() {
  local rules_json position slots moxes
  command -v pvesh >/dev/null 2>&1 || return 0
  slots="${BMAC_SLOT_FIRST}-${BMAC_SLOT_LAST}"
  moxes="${BMAC_MOX_FIRST}-$(mox_last)"
  rules_json="$(pvesh get "/nodes/$BMAC_HOST/firewall/rules" --output-format json)"
  while IFS= read -r position; do
    pvesh delete "/nodes/$BMAC_HOST/firewall/rules/$position"
  done < <(
    jq -r --arg prefix "$FIREWALL_COMMENT_PREFIX" '
      [.[] | select(
        (.comment // "") | startswith($prefix)
      )] | sort_by(.pos) | reverse | .[].pos
    ' <<<"$rules_json"
  )
  pvesh create "/nodes/$BMAC_HOST/firewall/rules" \
    --pos 0 --type forward --action ACCEPT --enable 1 --source "$slots" \
    --comment "$FIREWALL_COMMENT_PREFIX forward from VM slots"
  pvesh create "/nodes/$BMAC_HOST/firewall/rules" \
    --pos 0 --type forward --action ACCEPT --enable 1 --source "$moxes" \
    --comment "$FIREWALL_COMMENT_PREFIX forward from mox hosts"
}

install_units() {
  cat >/etc/systemd/system/app-ha-guest-network.service <<EOF
[Unit]
Description=BMAC shared guest gateway, egress NAT and routing tables
After=network-online.target networking.service
Wants=network-online.target
Before=pve-guests.service

[Service]
Type=oneshot
ExecStart=${INSTALL_DIR}/guest_network.sh apply
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
  cat >/etc/systemd/system/app-ha-egress-health.service <<EOF
[Unit]
Description=BMAC guest egress health and fallback through another mox host
After=app-ha-guest-network.service
Requires=app-ha-guest-network.service

[Service]
Type=simple
ExecStart=/usr/bin/python3 -I ${INSTALL_DIR}/egress_health.py run
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
  cat >/etc/systemd/system/app-ha-transfer-counter.service <<EOF
[Unit]
Description=BMAC monthly public-interface transfer counter

[Service]
Type=oneshot
ExecStart=/usr/bin/python3 -I ${INSTALL_DIR}/transfer_counter.py tick
EOF
  cat >/etc/systemd/system/app-ha-transfer-counter.timer <<'EOF'
[Unit]
Description=Update the BMAC transfer counter every minute

[Timer]
OnBootSec=30s
OnUnitActiveSec=1min
AccuracySec=5s

[Install]
WantedBy=timers.target
EOF
  systemctl daemon-reload
}

# A bridge reload (ifreload) could detach the veth from the bridge; the
# bridge's post-up hook reattaches it at once, and the health service checks
# it every few seconds as well.
install_post_up_hook() {
  local hook="    post-up ${INSTALL_DIR}/guest_network.sh ensure-gateway || true"
  [[ -f "$PRIVATE_CFG" ]] || die "$PRIVATE_CFG is missing; configure the private network first"
  grep -Fq "guest_network.sh ensure-gateway" "$PRIVATE_CFG" && return 0
  printf '%s\n' "$hook" >>"$PRIVATE_CFG"
}

# Add the interface names this host knows (recorded when host setup configured
# the private network) to the workstation-provided settings.
complete_settings() {
  local file="$1" public_nic private_nic public_if
  public_nic="$(<"/etc/app-ha-public-nic")" || die "/etc/app-ha-public-nic is missing"
  private_nic="$(<"/etc/app-ha-private-nic")" || die "/etc/app-ha-private-nic is missing"
  public_if="$(basename "$(readlink -f "/sys/class/net/$public_nic/master" 2>/dev/null || true)")"
  [[ -d "/sys/class/net/$public_if/bridge" ]] ||
    die "public NIC $public_nic is not a port of a bridge"
  sed -i -E '/^BMAC_(PUBLIC_NIC|PRIVATE_NIC|PUBLIC_IF)=/d' "$file"
  printf 'BMAC_PUBLIC_NIC=%s\nBMAC_PRIVATE_NIC=%s\nBMAC_PUBLIC_IF=%s\n' \
    "$public_nic" "$private_nic" "$public_if" >>"$file"
}

command_configure() {
  local source="${1:?settings file is required}"
  complete_settings "$source"
  load_settings "$source"
  install -d -m 0755 /etc/app-ha /etc/nftables.d
  install -m 0644 "$source" "${SETTINGS}.new"
  mv -f "${SETTINGS}.new" "$SETTINGS"
  render_sysctl >"${SYSCTL_FILE}.new"
  mv -f "${SYSCTL_FILE}.new" "$SYSCTL_FILE"
  render_nft >"${NFT_FILE}.new"
  nft -c -f "${NFT_FILE}.new"
  mv -f "${NFT_FILE}.new" "$NFT_FILE"
  install_post_up_hook
  reconcile_firewall_rules
  install_units
  /usr/bin/python3 -I "${INSTALL_DIR}/egress_health.py" validate-targets
  systemctl enable app-ha-guest-network.service app-ha-egress-health.service \
    app-ha-transfer-counter.timer
  systemctl restart app-ha-guest-network.service
  systemctl restart app-ha-egress-health.service
  systemctl start app-ha-transfer-counter.timer
  command_verify
}

command_verify() {
  load_settings
  local errors=0 peer_master
  check() {
    if ! "$@" >/dev/null 2>&1; then
      printf 'FAILED: %s\n' "$*" >&2
      errors=$((errors + 1))
    fi
  }
  check test "$(sysctl -n net.ipv4.ip_forward)" = 1
  check test "$(cat "/sys/class/net/$GATEWAY_IF/address" 2>/dev/null)" = "$BMAC_GUEST_GATEWAY_MAC"
  check grep -Fq " ${BMAC_GUEST_GATEWAY_IP}/32 " <(ip -4 -o address show dev "$GATEWAY_IF")
  peer_master="$(basename "$(readlink -f "/sys/class/net/$GATEWAY_PEER/master" 2>/dev/null || true)")"
  check test "$peer_master" = "$BMAC_PRIVATE_BRIDGE"
  check grep -Fq "lookup $GUEST_EGRESS_TABLE" <(ip rule show)
  check test -n "$(ip -4 route show table "$GUEST_EGRESS_TABLE" default)"
  check nft list table bridge app_ha_guest_gateway
  check nft list table ip app_ha_guest_egress
  check systemctl is-active app-ha-guest-network.service
  check systemctl is-active app-ha-egress-health.service
  check systemctl is-active app-ha-transfer-counter.timer
  # The gateway address must not be held by any other interface.
  check test "$(ip -4 -o address show | awk -v ip="${BMAC_GUEST_GATEWAY_IP}/" 'index($4, ip) == 1' | wc -l)" = 1
  ((errors == 0)) || die "$errors guest network check(s) failed"
  printf 'Guest gateway %s (%s) is local to %s; egress via %s.\n' \
    "$BMAC_GUEST_GATEWAY_IP" "$BMAC_GUEST_GATEWAY_MAC" "$BMAC_HOST" \
    "$(ip -4 route show table "$GUEST_EGRESS_TABLE" default)"
}

main() {
  local command="${1:-}"
  shift || true
  case "$command" in
    configure) command_configure "$@" ;;
    apply) command_apply ;;
    ensure-gateway)
      load_settings
      ensure_gateway
      ;;
    verify) command_verify ;;
    render-nft)
      load_settings "${1:-$SETTINGS}"
      render_nft
      ;;
    *) die "usage: guest_network.sh configure ENV_FILE|apply|ensure-gateway|verify|render-nft [ENV_FILE]" ;;
  esac
}

main "$@"
